"""
3D Mesh and Simulation Exporter module for Context Generator.
Exports generated context scenes into .OBJ, .STL, .GLTF, and .JSON formats
for downstream solar, radiation, wind CFD, and building environmental simulations.
"""

import json
import os
import numpy as np

